# B3-2a 診所的配置圖：上＝俯視圖（x −2～38 m、z −9～＋5）、下左＝剖面圖（從側面看鏡頭 B、天花板、窗戶的光、治療室）、下右＝配色。
# 用法：python3 art/design/b3/clinic_layout.py 輸出.png（ImageMagick 的 MVG；中文字用 STHeiti）
import math, subprocess, sys

OUT = sys.argv[1]
FONT = "/System/Library/Fonts/STHeiti Medium.ttc"
W, H = 1400, 1000
cmds = [f"viewbox 0 0 {W} {H}", f"font '{FONT}'"]


def rect(x0, y0, x1, y1, fill, stroke="none"):
    cmds.append(f"fill '{fill}' stroke '{stroke}' stroke-width 1 rectangle {x0:.1f},{y0:.1f} {x1:.1f},{y1:.1f}")


def line(x0, y0, x1, y1, color, width=1):
    cmds.append(f"stroke '{color}' stroke-width {width} fill none line {x0:.1f},{y0:.1f} {x1:.1f},{y1:.1f}")


def dot(x, y, r, color):
    cmds.append(f"fill '{color}' stroke none circle {x:.1f},{y:.1f} {x + r:.1f},{y:.1f}")


def text(x, y, s, size=13, color="#e8e8e8"):
    s = s.replace("'", "\\'")
    cmds.append(f"stroke none fill '{color}' font-size {size} text {x:.1f},{y:.1f} '{s}'")


# ---------- 俯視圖：1 m＝33 px；x=−2 在左；z=+5 在上（鏡頭這一側），往下是 z 變小（往裡面） ----------
PX, OX, OY = 33.0, 30.0, 60.0
def P(x, z):
    return OX + (x + 2) * PX, OY + (5 - z) * PX

text(20, 34, "俯視圖（上＝鏡頭這一側，下＝後牆；單位公尺；區域 x 0～36；天花板 3 m，鏡頭 B 在天花板下面）", 19)
rect(*P(-2, 5), *P(38, -9), "#1d2224")
rect(*P(0, 4.2), *P(36, -5.0), "#7a6e56")                       # 地板（50 cm 地磚）
for x in range(0, 37):
    line(*P(x, 4.2), *P(x, -5.0), "#6e6450")
rect(*P(0, 1.5), *P(36, -1.5), "#8a7e64")                       # 走道（主角能走的）
text(P(0.2, 0)[0], P(0, 0.3)[1], "走道 z −1.5～＋1.5", 12, "#2a2418")
rect(*P(0, -5.0), *P(36, -5.4), "#a0946e", "#c8bc98")           # 後牆（z −5）
rect(*P(-0.4, 4.2), *P(0, -5.4), "#a0946e"); rect(*P(36, 4.2), *P(36.4, -5.4), "#a0946e")   # 左右牆
# 後牆上的開口與窗戶
rect(*P(0.2, -4.9), *P(2.4, -5.5), "#e0a050")                   # 正門（鐵捲門拉起一半，外面是黃昏的街道）
text(P(0.1, -5.9)[0], P(0, -5.9)[1] + 6, "正門（回街道）", 12, "#f0c080")
for x0, x1 in ((4.2, 6.2), (12.6, 14.6), (23.8, 25.8), (29.6, 31.6)):
    rect(*P(x0, -4.95), *P(x1, -5.45), "#d8b060")               # 窗戶（破的、外面有爬藤）
    for k in range(5):                                           # 斜照進來的光
        line(*P(x0 + 0.3 * k, -5.0), *P(x0 + 1.6 + 0.3 * k, -1.2), "#e0b06060", 2)
text(P(4.0, -6.0)[0], P(0, -6.0)[1] + 6, "窗戶（破的）＋斜照進來的光 ×4", 12, "#f0c080")
rect(*P(19.8, -4.9), *P(20.8, -5.5), "#2a2418")                 # 治療室的門（開著）
rect(*P(18.6, -5.4), *P(22.6, -8.4), "#6a604a", "#c8bc98")      # 治療室（後牆後面的小房間）
text(P(18.8, -6.5)[0], P(0, -6.5)[1], "治療室（牆上的發音圖卡、", 12)
text(P(18.8, -7.1)[0], P(0, -7.1)[1], "桌上倒著的名牌、小窗）", 12)
rect(*P(21.4, -8.3), *P(22.4, -8.5), "#d8b060")
rect(*P(33.1, -4.9), *P(34.1, -5.5), "#5a4430")                 # 後門（木門、上面有出口牌）
text(P(32.0, -5.9)[0], P(0, -5.9)[1] + 6, "後門（離開診所）", 12, "#f0c080")
# 靠牆的家具（z −3.2～−4.8）
furn = [(2.8, 5.2, -4.0, -4.8, "#4a4038", "候診椅 ×3"), (5.6, 7.2, -4.2, -4.8, "#56603a", "盆栽（枯）"),
        (10.4, 13.4, -3.0, -4.4, "#5a4630", "櫃台（電話、螢幕、病歷）"), (10.2, 13.6, -4.6, -4.95, "#4a3a28", "病歷櫃"),
        (15.0, 15.8, -2.6, -3.3, "#6a6458", "輪椅"), (16.4, 16.9, -2.9, -3.4, "#9a9488", "點滴架"),
        (22.6, 24.8, -4.0, -4.8, "#4a4038", "候診椅 ×3"), (25.4, 25.9, -3.5, -4.0, "#9a9488", "點滴架"),
        (29.0, 29.8, -3.3, -4.0, "#6a6458", "輪椅"), (30.0, 32.4, -4.2, -4.9, "#c8c0a8", "推車、紙箱")]
for x0, x1, z0, z1, c, lab in furn:
    rect(*P(x0, z0), *P(x1, z1), c, "#c8bc98")
    text(P(x0, z0)[0], P(0, z0)[1] - 4, lab, 11, "#e0d8c0")
# 布簾（天花板的軌道，半拉開）
for x0, x1 in ((6.4, 8.2), (18.6, 19.6)):
    line(*P(x0, -2.6), *P(x1, -2.6), "#9aaa9a", 4)
    text(P(x0, -2.6)[0], P(0, -2.6)[1] + 14, "布簾", 11, "#c0d0c0")
# 互動點
pts = [(1.1, "回街道（正門）", "#e0b040"), (9.4, "藥櫃（錄音筆）", "#e0b040"), (20.3, "治療室（門口）", "#e0b040"),
       (27.3, "診療椅（旁邊有圓凳）", "#e0b040"), (33.6, "離開診所（後門）", "#e0b040")]
for x, lab, c in pts:
    dot(*P(x, -1.85), 5, c)
    text(P(x, -1.85)[0] + 7, P(x, -1.85)[1] - 6, lab, 12, "#f0d080")
rect(*P(8.7, -2.3), *P(10.1, -2.75), "#c8c0a8", "#ffffff")       # 藥櫃（玻璃門，錄音筆在中間那層）
rect(*P(26.6, -2.2), *P(27.9, -2.9), "#5a7a7a", "#ffffff")       # 診療椅
rect(*P(28.0, -2.3), *P(28.4, -2.7), "#4a4038", "#ffffff")       # 旁邊的小圓凳
# 擔架床（擋路，可以從前面或後面繞）
cmds.append(f"push graphic-context translate {P(14.8, 0.3)[0]:.1f},{P(14.8, 0.3)[1]:.1f} rotate -8")
rect(-1.0 * PX, -0.35 * PX, 1.0 * PX, 0.35 * PX, "#8a9090", "#ff9a3a")
cmds.append("pop graphic-context")
text(P(13.6, 1.0)[0], P(0, 1.0)[1] - 4, "擔架床（擋路，前後都能繞）", 12, "#ffb070")
# 前景（z +2.2 地上小物、+3.5 吊下來的東西）
for x, lab in ((4.7, "藥罐"), (10.0, "落葉"), (17.2, "病歷夾"), (24.2, "紙"), (29.7, "落葉"), (31.7, "藥罐"), (35.0, "碎玻璃")):
    dot(*P(x, 2.2), 3, "#a08a70")
    text(P(x, 2.2)[0] + 4, P(x, 2.2)[1] + 4, lab, 10, "#c0b0a0")
for x, lab in ((6.4, "布簾（前景）"), (13.0, "爬藤（從天花板垂下）"), (16.8, "爬藤"), (23.6, "布簾（前景）")):
    rect(*P(x - 0.5, 3.6), *P(x + 0.5, 3.3), "#56603a")
    text(P(x - 0.5, 3.6)[0], P(0, 3.6)[1] - 3, lab, 10, "#b8c890")
for x in range(0, 37, 6):
    text(P(x, -9)[0] - 6, P(0, -9)[1] + 16, f"{x}", 11, "#888")
# 鏡頭 B 在主角深度的視野（主角在 x 9.4）
line(*P(9.4 - 3.93, 0), *P(9.4 + 3.93, 0), "#ff8060", 2)
text(P(9.4 - 3.9, 0)[0], P(0, -0.6)[1], "鏡頭 B 在走道看得到約 7.9 m 寬", 11, "#ff9a80")

# ---------- 剖面圖：1 m＝28 px；z=+8 在左、z=−9 在右 ----------
SX, SOX, SOY = 40.0, 40.0, 960.0
def S(z, y):
    return SOX + (8 - z) * SX, SOY - y * SX

text(20, 610, "剖面圖（側面看：左＝鏡頭，右＝後牆與治療室）", 17)
rect(*S(4.2, 0), *S(-8.4, -0.3), "#7a6e56")                    # 地板
rect(*S(4.2, 3.0), *S(-5.0, 3.2), "#8a8270")                    # 天花板（輕鋼架，有幾片掉下來）
text(S(3.0, 3.2)[0], S(0, 3.2)[1] - 6, "天花板 3 m（輕鋼架，幾片掉了、日光燈管垂下來）", 12)
rect(*S(-5.0, 3.2), *S(-5.4, 0), "#a0946e")                     # 後牆
rect(*S(-5.0, 2.4), *S(-5.4, 1.0), "#d8b060")                   # 窗戶
rect(*S(-5.4, 2.6), *S(-8.4, 2.8), "#8a8270"); rect(*S(-8.4, 2.8), *S(-8.7, 0), "#a0946e")   # 治療室
text(S(-5.8, 1.6)[0], S(0, 1.6)[1], "治療室", 12)
for k in range(4):                                               # 窗戶的光，斜斜照到走道
    line(*S(-5.2, 2.3 - k * 0.3), *S(-1.0, 0.0 + k * 0.05), "#e0b06090", 3)
text(S(-0.6, 2.6)[0], S(0, 2.6)[1], "窗外的夕陽光斜照進來、落在走道上", 12, "#f0c080")
rect(*S(-4.0, 0.95), *S(-4.8, 0), "#4a4038")                    # 候診椅
rect(*S(-2.3, 1.8), *S(-2.75, 0), "#c8c0a8")                    # 藥櫃
text(S(-2.0, 2.05)[0] - 10, S(0, 2.05)[1], "藥櫃 1.8 m", 12)
p, q = S(1.5, 0); r, s = S(-1.5, 0)
line(p, q - 3, r, s - 3, "#e0b040", 4)
rect(*S(0.1, 1.5), *S(-0.1, 0), "#c8b890")
rect(*S(3.7, 3.0), *S(3.3, 1.6), "#56603a")                     # 前景的爬藤
text(S(3.9, 1.3)[0], S(0, 1.3)[1], "前景爬藤", 12, "#b8c890")
p, q = S(7.17, 2.23)
dot(p, q, 6, "#ff8060")
text(p - 20, q - 12, "鏡頭 B", 12, "#ff9a80")
for ang in (15, -25):
    dz = -9 - 7.17
    r, s = S(-9, 2.23 + math.tan(math.radians(ang)) * abs(dz))
    line(p, q, r, s, "#ff806080", 1)
text(S(2.0, 4.2)[0], S(0, 4.2)[1], "↑ 畫面上方會看到天花板（和停車場一樣）", 12)

# ---------- 配色 ----------
text(820, 610, "配色（固有色；暗的感覺交給燈光）", 17)
pal = [("#a0946e", "牆（灰泥、剝落）"), ("#8a7e64", "地磚"), ("#5a4630", "木頭（櫃台、門）"), ("#c8c0a8", "藥櫃、推車（米白）"),
       ("#56603a", "爬藤"), ("#3e4a2a", "爬藤（暗）"), ("#7a8a7a", "布簾（淡青灰）"), ("#5a7a7a", "診療椅（青綠皮面）"),
       ("#9a9488", "金屬（點滴架、輪椅）"), ("#8a8270", "天花板"), ("#e0b060", "窗外的光"), ("#5a1a14", "血跡")]
for i, (c, n) in enumerate(pal):
    x = 820 + (i % 2) * 290
    y = 640 + (i // 2) * 42
    rect(x, y, x + 54, y + 32, c, "#888")
    text(x + 64, y + 22, f"{n}  {c}", 13)

mvg = OUT + ".mvg"
open(mvg, "w", encoding="utf-8").write("\n".join(cmds) + "\n")
subprocess.run(["magick", "-size", f"{W}x{H}", "xc:#1d2224", "-draw", f"@{mvg}", OUT], check=True)
