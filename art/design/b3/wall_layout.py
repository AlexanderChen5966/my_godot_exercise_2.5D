# B3-6a 牆前的配置圖：上＝俯視圖（x −2～38 m、z −9～＋5）、下左＝剖面圖（從側面看鏡頭 B、牆上的字）、下右＝配色。
# 用法：python3 art/design/b3/wall_layout.py 輸出.png（ImageMagick 的 MVG；中文字用 STHeiti）
# 互動點位置照 Wall3D（B1 由 2D 轉換）不變：牆 23.44；出生點 x 3.4；沒有出口（結局由「最後的動作」的選項決定）。
# 字的高度照 B3-5c 舊家學到的：主角頭頂擋住後牆約 1.2 m 以下、互動提示在 1.45～1.6 m，字放在 1.7～2.5 m。
import math, subprocess, sys

OUT = sys.argv[1]
FONT = "/System/Library/Fonts/STHeiti Medium.ttc"
W, H = 1400, 1060
cmds = [f"viewbox 0 0 {W} {H}", f"font '{FONT}'"]


def rect(x0, y0, x1, y1, fill, stroke="none"):
    cmds.append(f"fill '{fill}' stroke '{stroke}' stroke-width 1 rectangle {x0:.1f},{y0:.1f} {x1:.1f},{y1:.1f}")


def line(x0, y0, x1, y1, color, width=1):
    cmds.append(f"stroke '{color}' stroke-width {width} fill none line {x0:.1f},{y0:.1f} {x1:.1f},{y1:.1f}")


def dot(x, y, r, color):
    cmds.append(f"fill '{color}' stroke none circle {x:.1f},{y:.1f} {x + r:.1f},{y:.1f}")


def poly(pts, fill):
    cmds.append(f"fill '{fill}' stroke none polygon " + " ".join(f"{x:.1f},{y:.1f}" for x, y in pts))


def text(x, y, s, size=13, color="#e8e8e8"):
    s = s.replace("'", "\\'")
    cmds.append(f"stroke none fill '{color}' font-size {size} text {x:.1f},{y:.1f} '{s}'")


WALL = -3.6                                                # 後牆
# ---------- 俯視圖：1 m＝33 px（x）、30 px（z） ----------
PX, PZ, OX, OY = 33.0, 30.0, 30.0, 60.0
def P(x, z):
    return OX + (x + 2) * PX, OY + (5 - z) * PZ

text(20, 34, "俯視圖（上＝鏡頭這一側，下＝後牆與後面的房間；單位公尺；區域 x 0～36；天花板 2.8 m，中段塌了）", 19)
rect(*P(-2, 5), *P(38, -9), "#16171a")
rect(*P(0, 4.2), *P(36, WALL), "#4a4844")                       # 水泥地
rect(*P(0, 1.5), *P(36, -1.5), "#54524c")
text(P(0.2, 0)[0], P(0, 0.3)[1], "走道 z −1.5～＋1.5", 12, "#c8c4b8")
rect(*P(0, WALL), *P(36, WALL - 0.25), "#6a665c", "#a8a294")    # 後牆
rect(*P(-0.4, 4.2), *P(0, WALL - 0.25), "#6a665c"); rect(*P(36, 4.2), *P(36.4, WALL - 0.25), "#6a665c")
# 天花板塌掉的一段（月光從這裡照下來）
poly([P(18.0, 1.5), P(26.5, 1.5), P(27.5, WALL), P(19.0, WALL)], "#a8c0e026")
text(P(18.6, 1.2)[0], P(0, 1.2)[1], "天花板塌掉的一段（x 19～27）：看得到屋頂的破洞", 11, "#b8c8e0")
# 牆上的灰泥與炭筆字（23.44）
rect(*P(21.9, WALL + 0.06), *P(25.0, WALL - 0.02), "#b8b0a0")
text(P(17.0, -4.35)[0], P(0, -4.35)[1] + 6, "補過的灰泥牆（x 21.9～25）＋", 12, "#e8e0d0")
text(P(17.0, -5.05)[0], P(0, -5.05)[1] + 6, "炭筆字「I'M STILL HERE」（1.7～2.5 m）", 12, "#e8e0d0")
poly([P(22.4, -3.5), P(24.6, -3.5), P(25.8, -0.6), P(21.6, -0.6)], "#c8d8ff30")
text(P(19.2, -0.9)[0] - 30, P(0, -0.9)[1] - 8, "月光照在牆上 ↓", 11, "#c8d8ff")
dot(*P(23.9, -3.3), 3, "#202020")
text(P(24.2, -3.0)[0], P(0, -3.0)[1], "掉在牆腳的炭筆", 10, "#c0c0c0")
# 門洞 1（左，暗的，來的方向）
rect(*P(5.7, WALL + 0.05), *P(6.8, WALL - 0.3), "#0c0c0e")
rect(*P(4.6, WALL - 0.3), *P(8.0, -6.0), "#101114", "#4a4844")
text(P(4.7, -4.4)[0], P(0, -4.4)[1] + 6, "門洞 1：暗的走廊（來的方向）", 11, "#a0a0a8")
# 門洞 2（右）＋後面的房間：暖色的窗光、地上的熊布偶（原插畫）
rect(*P(27.5, WALL + 0.05), *P(28.7, WALL - 0.3), "#2a2018")
rect(*P(26.0, WALL - 0.3), *P(31.5, -7.4), "#3a2e22", "#a8a294")
rect(*P(29.6, -7.3), *P(30.8, -7.5), "#ffc070")
poly([P(29.6, -7.3), P(30.8, -7.3), P(29.4, -4.6), P(27.9, -4.6)], "#ffc07030")
dot(*P(28.9, -5.2), 5, "#8a6a4a")
text(P(26.2, -4.5)[0], P(0, -4.5)[1] + 6, "門洞 2 後面的房間：", 11, "#f0c890")
text(P(26.2, -5.9)[0], P(0, -5.9)[1] + 6, "暖色的窗光、熊布偶", 11, "#f0c890")
# 空椅子（面向牆）
cmds.append(f"push graphic-context translate {P(11.0, -2.6)[0]:.1f},{P(11.0, -2.6)[1]:.1f} rotate -15")
rect(-0.25 * PX, -0.25 * PZ, 0.25 * PX, 0.25 * PZ, "#4a3a2c", "#c8b898")
rect(-0.25 * PX, -0.32 * PZ, 0.25 * PX, -0.25 * PZ, "#6a5440")
cmds.append("pop graphic-context")
text(P(9.4, -3.3)[0], P(0, -3.3)[1] + 4, "一張空椅子（面向牆）", 11, "#e0d0b0")
# 其他：牆面剝落露出磚、地上的碎灰泥、倒下的木板
for x in (2.5, 9.0, 15.5, 30.5, 34.0):
    rect(*P(x - 0.5, WALL + 0.05), *P(x + 0.5, WALL), "#8a4a38")
text(P(9.5, -4.4)[0], P(0, -4.4)[1] + 6, "灰泥剝落露出磚（紅色）", 11, "#d09080")
for x in (16.5, 33.0):
    line(*P(x - 1.0, -3.0), *P(x + 0.6, -2.4), "#7a6a52", 4)
text(P(15.2, -2.0)[0], P(0, -2.0)[1] + 4, "倒下的木板", 10, "#c8b898")
# 互動點
dot(*P(23.44, -1.85), 5, "#e0b040")
text(P(23.44, -1.85)[0] + 7, P(23.44, -1.85)[1] - 6, "牆（最後的動作：結局 A／B／C）", 12, "#f0d080")
# 前景
for x, lab in ((6.25, "碎灰泥"), (29.7, "碎灰泥"), (22.2, "炭筆")):
    dot(*P(x, 2.4), 3, "#a09890")
    text(P(x, 2.4)[0] + 4, P(x, 2.4)[1] + 4, lab, 10, "#c0b8b0")
for x, lab in ((7.2, "斷牆（前景、低）"), (34.5, "斷牆（前景、低）")):
    rect(*P(x - 0.6, 3.6), *P(x + 0.6, 3.3), "#3a3834")
    text(P(x - 0.6, 3.6)[0], P(0, 3.6)[1] - 3, lab, 10, "#b0aca0")
text(P(2.6, -0.9)[0], P(0, -0.9)[1], "出生點 x 3.4", 11, "#a0a0a0")
text(P(31.5, 0.6)[0], P(0, 0.6)[1], "沒有出口（結局由選項決定）", 11, "#a0a0a0")
for x in range(0, 37, 6):
    text(P(x, -9)[0] - 6, P(0, -9)[1] + 16, f"{x}", 11, "#888")

# ---------- 剖面圖：1 m＝45 px；z=+8 在左、z=−8 在右（切在 x 23.4：牆上的字） ----------
SX, SOX, SOY = 45.0, 40.0, 1020.0
def S(z, y):
    return SOX + (8 - z) * SX, SOY - y * SX

text(20, 560, "剖面圖（切在牆上的字 x 23.4；左＝鏡頭，右＝後牆）", 17)
rect(*S(4.2, 0), *S(WALL, -0.2), "#4a4844")
rect(*S(4.2, 2.8), *S(1.6, 2.95), "#4a4640")
text(S(4.0, 3.0)[0], S(0, 3.0)[1] - 6, "天花板（中段塌了，只剩前緣）", 12)
poly([S(1.6, 2.95), S(0.8, 2.6), S(1.2, 2.5), S(1.6, 2.8)], "#4a4640")
rect(*S(WALL, 2.95), *S(WALL - 0.25, 0), "#6a665c")
rect(*S(WALL + 0.03, 2.6), *S(WALL - 0.02, 0.3), "#b8b0a0")
rect(*S(WALL + 0.05, 2.5), *S(WALL - 0.03, 1.7), "#202020")
text(S(WALL + 3.6, 2.2)[0], S(0, 2.2)[1], "炭筆字 1.7～2.5 m →", 12, "#e8e0d0")
text(S(WALL + 3.6, 1.0)[0], S(0, 1.0)[1], "灰泥 0.3～2.6 m →", 12, "#c8c0b0")
line(*S(-1.0, 5.5), *S(WALL + 0.1, 2.0), "#c8d8ff", 2)
line(*S(0.2, 5.5), *S(WALL + 0.1, 1.2), "#c8d8ff", 2)
text(S(1.0, 5.4)[0], S(0, 5.4)[1], "月光（從塌掉的屋頂斜照在牆上）", 12, "#c8d8ff")
p, q = S(1.5, 0); r, s = S(-1.5, 0)
line(p, q - 3, r, s - 3, "#e0b040", 4)
rect(*S(0.1, 1.6), *S(-0.1, 0), "#7a8a70")
text(S(1.2, 1.9)[0], S(0, 1.9)[1], "主角", 11, "#c0d0b0")
p, q = S(7.17, 2.23)                                       # 鏡頭 B：原本的角度（往下 5°、看的高度 1.6 m）
dot(p, q, 6, "#ff8060")
text(p - 20, q - 12, "鏡頭 B", 12, "#ff9a80")
for ang in (15, -25):
    dz = -8 - 7.17
    r, s = S(-8, 2.23 + math.tan(math.radians(ang)) * abs(dz))
    line(p, q, r, s, "#ff806080", 1)
r, s = S(WALL, 2.23 - (2.23 - 1.6) * (7.17 - WALL) / 7.17)
line(p, q, r, s, "#ffffff60", 1)
text(S(5.5, 0.8)[0], S(0, 0.8)[1], "主角頭頂擋住牆上 1.2 m 以下", 11, "#c0c0c0")

# ---------- 配色 ----------
text(820, 560, "配色（固有色；月光、暖光交給燈光）", 17)
pal = [("#6a665c", "舊牆（灰、髒）"), ("#b8b0a0", "補過的灰泥（字的底）"), ("#202020", "炭筆字"), ("#8a4a38", "剝落露出的磚"),
       ("#4a4844", "水泥地"), ("#4a3a2c", "椅子、木板"), ("#4a4640", "天花板"), ("#c8d8ff", "月光（冷）"),
       ("#ffc070", "隔壁房間的窗光（暖）"), ("#8a6a4a", "熊布偶"), ("#16171a", "陰影"), ("#7a8a70", "主角的手（灰綠）")]
for i, (c, n) in enumerate(pal):
    x = 820 + (i % 2) * 290
    y = 590 + (i // 2) * 42
    rect(x, y, x + 54, y + 32, c, "#888")
    text(x + 64, y + 22, f"{n}  {c}", 13)
text(820, 862, "燈光：最暗的一區。冷色的月光從塌掉的屋頂照在牆上的字；", 13, "#c0c0c0")
text(820, 884, "門洞 2 後面的房間有暖色的窗光（原插畫右邊）；主角的手電筒。", 13, "#c0c0c0")
text(820, 906, "光束、灰塵、事件運鏡（選結局時）留到 B5。", 13, "#c0c0c0")

mvg = OUT + ".mvg"
open(mvg, "w", encoding="utf-8").write("\n".join(cmds) + "\n")
subprocess.run(["magick", "-size", f"{W}x{H}", "xc:#1a1c1e", "-draw", f"@{mvg}", OUT], check=True)
