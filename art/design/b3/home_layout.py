# B3-5a 舊家的配置圖：上＝俯視圖（x −2～38 m、z −9～＋5）、下左＝剖面圖（從側面看鏡頭 B、窗外的女兒、牆上的字）、下右＝配色。
# 用法：python3 art/design/b3/home_layout.py 輸出.png（ImageMagick 的 MVG；中文字用 STHeiti）
# 互動點與擋路的衣櫃位置照 Home3D（B1 由 2D 轉換）不變；牆上的字、窗戶、女兒的高度重新設計（B1 從 2D 像素換算成 2.7～3.9 m 高）。
import math, subprocess, sys

OUT = sys.argv[1]
FONT = "/System/Library/Fonts/STHeiti Medium.ttc"
W, H = 1400, 1060
cmds = [f"viewbox 0 0 {W} {H}", f"font '{FONT}'"]


def rect(x0, y0, x1, y1, fill, stroke="none"):
    cmds.append(f"fill '{fill}' stroke '{stroke}' stroke-width 1 rectangle {x0:.1f},{y0:.1f} {x1:.1f},{y1:.1f}")


def line(x0, y0, x1, y1, color, width=1):
    cmds.append(f"stroke '{color}' stroke-width {width} fill none line {x0:.1f},{y0:.1f} {x1:.1f},{y1:.1f}")


def dot(x, y, r, color):
    cmds.append(f"fill '{color}' stroke none circle {x:.1f},{y:.1f} {x + r:.1f},{y:.1f}")


def poly(pts, fill):
    cmds.append(f"fill '{fill}' stroke none polygon " + " ".join(f"{x:.1f},{y:.1f}" for x, y in pts))


def text(x, y, s, size=13, color="#e8e8e8"):
    s = s.replace("'", "\\'")
    cmds.append(f"stroke none fill '{color}' font-size {size} text {x:.1f},{y:.1f} '{s}'")


WALL = -3.6                                                # 後牆
# ---------- 俯視圖：1 m＝33 px（x）、30 px（z） ----------
PX, PZ, OX, OY = 33.0, 30.0, 30.0, 60.0
def P(x, z):
    return OX + (x + 2) * PX, OY + (5 - z) * PZ

text(20, 34, "俯視圖（上＝鏡頭這一側，下＝後牆與後面的房間、窗外；單位公尺；區域 x 0～36；天花板 2.7 m）", 19)
rect(*P(-2, 5), *P(38, -9), "#1c1a18")
rect(*P(0, 4.2), *P(36, WALL), "#5a4632")                       # 木地板
for x in range(0, 36):
    line(*P(x + 0.5 * (x % 2), 4.2), *P(x + 0.5 * (x % 2), WALL), "#4e3c2a")
rect(*P(0, 1.5), *P(36, -1.5), "#64503a")
text(P(0.2, 0)[0], P(0, 0.3)[1], "走道 z −1.5～＋1.5（客廳 → 走廊 → 餐廳）", 12, "#d8c8a8")
rect(*P(0, WALL), *P(36, WALL - 0.25), "#8a7a60", "#c8b898")    # 後牆
rect(*P(-0.4, 4.2), *P(0, WALL - 0.25), "#8a7a60"); rect(*P(36, 4.2), *P(36.4, WALL - 0.25), "#8a7a60")
# 區域的分段
for x0, x1, lab in ((0, 12.5, "客廳（書架、照片、沙發、落地燈、矮桌）"), (12.5, 22.0, "走廊（倒下的衣櫃、女兒的房間）"), (22.0, 36.0, "餐廳與廚房（餐桌、流理台、冰箱、大窗、大門）")):
    text(P(x0 + 0.2, 4.95)[0], P(0, 4.95)[1] + 4, lab, 12, "#c8b898")
    if x0 > 0:
        line(*P(x0, 5.0), *P(x0, 4.2), "#8a7a60", 2)
# 牆上的蠟筆字（9.38，小孩的高度）＋照進來的光
rect(*P(8.2, WALL + 0.05), *P(10.6, WALL - 0.05), "#c03a2a")
text(P(7.6, -4.4)[0], P(0, -4.4)[1] + 6, "牆上的蠟筆字（0.7～1.6 m 高）", 12, "#ff8070")
poly([P(8.6, -3.55), P(10.2, -3.55), P(11.6, -0.5), P(9.6, -0.5)], "#ffd09030")
text(P(6.0, 1.0)[0], P(0, 1.0)[1], "天花板破洞照下來的夕陽 ↘", 11, "#ffd090")
dot(*P(9.0, -3.25), 5, "#a07050")
text(P(9.3, -2.95)[0], P(0, -2.95)[1], "熊", 10, "#d0b090")
# 女兒的房間（後牆後面，門開著）
rect(*P(17.4, WALL + 0.05), *P(18.5, WALL - 0.3), "#2a1e16")
rect(*P(15.8, WALL - 0.3), *P(20.6, -7.2), "#4a3a2c", "#c8b898")
text(P(16.0, -4.4)[0], P(0, -4.4)[1] + 6, "女兒的房間：小床（被子疊好）、", 11, "#e0d0b0")
text(P(16.0, -5.1)[0], P(0, -5.1)[1] + 6, "牆上的蠟筆畫（爸爸、媽媽、女孩）", 11, "#e0d0b0")
rect(*P(18.8, -5.8), *P(20.2, -6.9), "#8a6a7a", "#ffffff")
# 大窗與窗外（女兒在外面的人行道上）
rect(*P(26.4, WALL + 0.05), *P(29.2, WALL - 0.3), "#c8d0d8")
text(P(25.6, -4.4)[0], P(0, -4.4)[1] + 6, "大窗（窗台 0.9、上緣 2.1 m）", 11, "#c8d8e8")
rect(*P(22.0, WALL - 0.3), *P(36, -9), "#3a2e26")
rect(*P(22.0, -4.2), *P(36, -5.4), "#6a5e50")
text(P(30.0, -4.6)[0], P(0, -4.6)[1] + 4, "窗外的人行道", 10, "#c8bca8")
dot(*P(27.5, -4.8), 6, "#f0c080")
text(P(26.3, -5.7)[0], P(0, -5.7)[1] + 8, "窗外的女兒（27.5, z −4.8）", 12, "#ffd090")
text(P(22.4, -7.6)[0], P(0, -7.6)[1], "窗外：對街的房子剪影＋像素天空（黃昏）", 11, "#f0c080")
# 大門（出口）
rect(*P(33.0, WALL + 0.05), *P(34.2, WALL - 0.3), "#6a4a30")
text(P(32.6, -2.9)[0], P(0, -2.9)[1], "大門（離開）", 12, "#f0c080")
# 家具
furn = [(1.2, 2.6, -3.15, -3.55, "#5a4030", "書架"), (3.6, 7.0, -2.4, -3.3, "#5a4a3a", "沙發（破）"), (8.0, 8.4, -2.9, -3.3, "#3a3028", ""),
        (11.2, 12.8, -1.9, -2.7, "#5a4030", "矮桌（翻倒）"), (22.8, 25.0, -2.0, -3.0, "#6a4e34", "餐桌＋椅子"),
        (29.6, 32.4, -3.0, -3.55, "#8a8070", "流理台"), (34.8, 35.6, -2.8, -3.55, "#a09888", "冰箱")]
for x0, x1, z0, z1, c, lab in furn:
    rect(*P(x0, z0), *P(x1, z1), c, "#c8b898")
    if lab:
        below = lab.startswith("矮桌")                            # 矮桌的字放下面，不壓到牆上的字
        text(P(x0, z1 if below else z0)[0], P(0, z1 if below else z0)[1] + (12 if below else -4), lab, 11, "#e0d0b0")
text(P(7.6, -2.75)[0] - 4, P(0, -2.75)[1] - 6, "落地燈", 10, "#e0d0b0")
for x in (4.7, 16.0, 21.2):
    rect(*P(x - 0.3, WALL + 0.06), *P(x + 0.3, WALL + 0.0), "#c8a070")
text(P(4.3, -3.9)[0], P(0, -3.9)[1] + 4, "照片", 10, "#e0c090")
# 互動點
pts = [(9.38, "牆上的字（記憶閃回）"), (17.97, "女兒的房間（門口）"), (25.78, "窗外的女兒（靠近就觸發）"), (33.59, "離開（大門）")]
for x, lab in pts:
    dot(*P(x, -1.85), 5, "#e0b040")
    text(P(x, -1.85)[0] + 7, P(x, -1.85)[1] - 6, lab, 12, "#f0d080")
# 倒下的衣櫃（擋路）
cmds.append(f"push graphic-context translate {P(13.75, 0.26)[0]:.1f},{P(13.75, 0.26)[1]:.1f} rotate 10")
rect(-0.9 * PX, -0.3 * PZ, 0.9 * PX, 0.3 * PZ, "#6a4a30", "#ff9a3a")
cmds.append("pop graphic-context")
text(P(12.2, 1.2)[0], P(0, 1.2)[1] - 2, "倒下的衣櫃（擋路，前後都能繞）", 12, "#ffb070")
# 前景
for x, lab in ((5.2, "蠟筆"), (8.75, "熊布偶"), (16.6, "相框"), (21.9, "蠟筆"), (28.9, "紙"), (32.0, "相框")):
    dot(*P(x, 2.3), 3, "#a09080")
    text(P(x, 2.3)[0] + 4, P(x, 2.3)[1] + 4, lab, 10, "#c0b0a0")
for x, lab in ((3.0, "垂下的天花板木條（前景）"), (13.0, "斷掉的門框（前景、低）"), (30.0, "垂下的天花板木條")):
    rect(*P(x - 0.5, 3.6), *P(x + 0.5, 3.3), "#6a5440")
    text(P(x - 0.5, 3.6)[0], P(0, 3.6)[1] - 3, lab, 10, "#d0c0a0")
text(P(2.6, -0.9)[0], P(0, -0.9)[1], "出生點 x 3.4", 11, "#a0a0a0")
for x in range(0, 37, 6):
    text(P(x, -9)[0] - 6, P(0, -9)[1] + 16, f"{x}", 11, "#888")

# ---------- 剖面圖：1 m＝45 px；z=+8 在左、z=−8 在右 ----------
SX, SOX, SOY = 45.0, 40.0, 1020.0
def S(z, y):
    return SOX + (8 - z) * SX, SOY - y * SX

text(20, 560, "剖面圖（側面看：左＝鏡頭，右＝後牆與窗外）", 17)
rect(*S(4.2, 0), *S(WALL, -0.2), "#5a4632")
rect(*S(4.2, 2.7), *S(WALL, 2.85), "#6a5a48")
text(S(3.4, 2.85)[0], S(0, 2.85)[1] - 6, "天花板 2.7 m（有破洞、木條垂下）", 12)
rect(*S(WALL, 2.85), *S(WALL - 0.25, 0), "#8a7a60")
rect(*S(WALL, 2.1), *S(WALL - 0.25, 0.9), "#c8d0d8")
text(S(WALL + 2.3, 1.95)[0], S(0, 1.95)[1], "大窗 →", 12, "#c8d8e8")
rect(*S(WALL + 0.02, 1.6), *S(WALL - 0.02, 0.7), "#c03a2a")
text(S(WALL + 2.6, 1.2)[0], S(0, 1.2)[1], "蠟筆字 0.7～1.6 m →", 12, "#ff8070")
rect(*S(-4.2, 0.1), *S(-5.4, 0), "#6a5e50")
rect(*S(-4.65, 1.25), *S(-4.95, 0.1), "#f0c080")
text(S(-4.0, 1.5)[0], S(0, 1.5)[1], "女兒（約 1.2 m）", 12, "#ffd090")
rect(*S(-7.5, 4.0), *S(-8.0, 0), "#4a3a30")
text(S(-6.2, 4.4)[0], S(0, 4.4)[1], "對街的房子", 11, "#c0a080")
p, q = S(1.5, 0); r, s = S(-1.5, 0)
line(p, q - 3, r, s - 3, "#e0b040", 4)
rect(*S(0.1, 1.6), *S(-0.1, 0), "#c8b890")
p, q = S(7.17, 2.23)                                       # 鏡頭 B：原本的角度（往下 5°、看的高度 1.6 m）
dot(p, q, 6, "#ff8060")
text(p - 20, q - 12, "鏡頭 B", 12, "#ff9a80")
for ang in (15, -25):
    dz = -8 - 7.17
    r, s = S(-8, 2.23 + math.tan(math.radians(ang)) * abs(dz))
    line(p, q, r, s, "#ff806080", 1)
text(S(7.5, 3.5)[0], S(0, 3.5)[1], "室內：鏡頭照原本的角度（往下 5°）", 12)

# ---------- 配色 ----------
text(820, 560, "配色（固有色；黃昏的光交給燈光）", 17)
pal = [("#8a7a60", "壁紙（剝落、水漬）"), ("#5a4632", "木地板"), ("#5a4030", "深色木頭（書架、門）"), ("#5a4a3a", "沙發（褪色的布）"),
       ("#c03a2a", "紅色蠟筆"), ("#6a5a48", "天花板"), ("#a09888", "冰箱、流理台"), ("#c8d0d8", "窗玻璃"),
       ("#a07050", "熊布偶"), ("#f0c080", "夕陽的光"), ("#3a2e26", "窗外（暗處）"), ("#2a1e16", "陰影")]
for i, (c, n) in enumerate(pal):
    x = 820 + (i % 2) * 290
    y = 590 + (i // 2) * 42
    rect(x, y, x + 54, y + 32, c, "#888")
    text(x + 64, y + 22, f"{n}  {c}", 13)
text(820, 862, "燈光：沒有電、很暗；夕陽從天花板破洞照在牆上的字、", 13, "#c0c0c0")
text(820, 884, "從大窗斜照進來（窗外是黃昏）；女兒的房間有一點窗光；", 13, "#c0c0c0")
text(820, 906, "主角的手電筒。灰塵粒子、光束留到 B5。", 13, "#c0c0c0")

mvg = OUT + ".mvg"
open(mvg, "w", encoding="utf-8").write("\n".join(cmds) + "\n")
subprocess.run(["magick", "-size", f"{W}x{H}", "xc:#1a1c1e", "-draw", f"@{mvg}", OUT], check=True)
