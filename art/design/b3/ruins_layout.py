# B3-4a 廢墟的配置圖：上＝俯視圖（x −2～38 m、z −14～＋5）、下左＝剖面圖（從側面看鏡頭 B、倒塌的樓、缺口後面的天空）、下右＝配色。
# 用法：python3 art/design/b3/ruins_layout.py 輸出.png（ImageMagick 的 MVG；中文字用 STHeiti）
# 互動點、擋路的拒馬位置照 Ruins3D（B1 由 2D 轉換）不變；同類、妻子（避難所）的事件靠這些位置觸發。
import math, subprocess, sys

OUT = sys.argv[1]
FONT = "/System/Library/Fonts/STHeiti Medium.ttc"
W, H = 1400, 1120
cmds = [f"viewbox 0 0 {W} {H}", f"font '{FONT}'"]


def rect(x0, y0, x1, y1, fill, stroke="none"):
    cmds.append(f"fill '{fill}' stroke '{stroke}' stroke-width 1 rectangle {x0:.1f},{y0:.1f} {x1:.1f},{y1:.1f}")


def line(x0, y0, x1, y1, color, width=1):
    cmds.append(f"stroke '{color}' stroke-width {width} fill none line {x0:.1f},{y0:.1f} {x1:.1f},{y1:.1f}")


def dot(x, y, r, color):
    cmds.append(f"fill '{color}' stroke none circle {x:.1f},{y:.1f} {x + r:.1f},{y:.1f}")


def poly(pts, fill):
    cmds.append(f"fill '{fill}' stroke none polygon " + " ".join(f"{x:.1f},{y:.1f}" for x, y in pts))


def text(x, y, s, size=13, color="#e8e8e8"):
    s = s.replace("'", "\\'")
    cmds.append(f"stroke none fill '{color}' font-size {size} text {x:.1f},{y:.1f} '{s}'")


# ---------- 俯視圖：1 m＝33 px（x）、30 px（z）；x=−2 在左；z=+5 在上（鏡頭這一側） ----------
PX, PZ, OX, OY = 33.0, 30.0, 30.0, 60.0
def P(x, z):
    return OX + (x + 2) * PX, OY + (5 - z) * PZ

text(20, 34, "俯視圖（上＝鏡頭這一側，下＝倒塌的樓與遠方；單位公尺；區域 x 0～36；戶外，看得到天空）", 19)
rect(*P(-2, 5), *P(38, -14), "#3a2a20")                          # 遠方（天空、剪影）
rect(*P(-2, 4.2), *P(38, 2.6), "#5e554a")                        # 前人行道（碎裂）
rect(*P(-2, 2.6), *P(38, -3.3), "#4a443c")                       # 馬路（裂縫、褪色的中線）
rect(*P(0, 1.5), *P(36, -1.5), "#544c42")                        # 走道
text(P(0.2, 0)[0], P(0, 0.3)[1], "走道 z −1.5～＋1.5（馬路）", 12, "#c8bca8")
for x in range(0, 36, 3):
    line(*P(x, 0.0), *P(x + 1.5, 0.0), "#b8a060", 3)             # 褪色的中線
rect(*P(-2, -3.3), *P(38, -5.2), "#6a5e50")                      # 後人行道
# 倒塌的樓：斷牆（高低不一）與缺口（看得到天空、遠處剪影）
blocks = [(0.0, 5.0, "高的空殼 8 m（窗洞、樓板外露）", "#4e4640"), (7.0, 11.5, "塌剩一層 3 m", "#5a524a"),
          (14.0, 18.5, "高的空殼 7 m（燒黑）", "#3e3a36"), (29.5, 36.0, "塌剩兩層 5 m", "#5a524a")]
for x0, x1, lab, c in blocks:
    rect(*P(x0, -5.2), *P(x1, -11.0), c, "#8a7e70")
    text(P(x0 + 0.2, -6.0)[0], P(0, -6.0)[1] + 4, lab, 11, "#d8ccb8")
for x0, x1 in ((5.0, 7.0), (11.5, 14.0), (18.5, 23.0)):
    poly([P(x0, -5.4), P(x1, -5.4), P(x1 - 0.3, -7.5), P(x0 + 0.5, -7.0)], "#6a5a48")    # 瓦礫堆
    text(P(x0, -8.4)[0], P(0, -8.4)[1], "缺口", 11, "#f0c080")
text(P(5.0, -12.6)[0], P(0, -12.6)[1], "缺口後面：遠處的樓房剪影＋黃昏的煙霧天空（借街道的遠景）", 12, "#f0c080")
# 避難所：鐵絲網圍欄（門開著）、後面的鐵皮屋＋亮著的窗、營火桶
rect(*P(23.0, -2.6), *P(29.5, -11.0), "#2e2a24")
line(*P(23.6, -2.6), *P(26.0, -2.6), "#a0a8b0", 3); line(*P(27.2, -2.6), *P(29.4, -2.6), "#a0a8b0", 3)
line(*P(23.6, -2.6), *P(23.6, -6.0), "#a0a8b0", 3); line(*P(29.4, -2.6), *P(29.4, -6.0), "#a0a8b0", 3)
line(*P(26.0, -2.6), *P(25.4, -1.9), "#a0a8b0", 2)                # 開著的門
text(P(23.7, -3.3)[0], P(0, -3.3)[1], "鐵絲網圍欄（上面有刺網、紅十字牌）", 11, "#c8d0d8")
rect(*P(24.6, -6.4), *P(28.6, -9.4), "#6a5a48", "#c8a070")
rect(*P(25.8, -6.35), *P(27.0, -6.55), "#ffc070")
text(P(24.7, -7.8)[0], P(0, -7.8)[1], "避難所（鐵皮屋，窗戶亮著）", 11, "#ffd090")
dot(*P(28.4, -4.8), 6, "#ff9a3a")
text(P(27.5, -5.3)[0], P(0, -5.3)[1] - 2, "營火", 11, "#ffb070")
# 路障（沙包＋鐵板）、火桶、電線桿
for x, lab in ((5.9, "路障（沙包、鐵板）"), (21.1, "路障")):
    rect(*P(x - 1.2, -2.7), *P(x + 1.2, -3.3), "#8a7a5a", "#d0c090")
    text(P(x - 1.2, -3.3)[0], P(0, -3.3)[1] + 14, lab, 11, "#e0d0a0")
for x in (4.7, 19.5):
    dot(*P(x, -2.4), 7, "#ff8a20")
    text(P(x, -2.4)[0] - 30, P(0, -2.4)[1] + 4, "火桶", 11, "#ffb070")
for x, ang in ((2.0, "歪"), (16.6, "歪"), (31.0, "")):
    dot(*P(x, -3.7), 4, "#8a6a4a")
    text(P(x, -3.7)[0] + 5, P(0, -3.7)[1] + 14, f"電線桿{('（' + ang + '）') if ang else ''}", 10, "#c0a080")
line(*P(2.0, -3.7), *P(16.6, -3.7), "#30302a", 1); line(*P(16.6, -3.7), *P(31.0, -3.7), "#30302a", 1)
# 燒毀的車（原插畫）
rect(*P(8.0, -2.0), *P(12.2, -3.2), "#3a2a20", "#9a7a5a")
text(P(8.0, -1.9)[0], P(0, -1.9)[1] - 2, "燒毀的車", 11, "#d0b090")
# 互動點
pts = [(12.5, "同類（靠近就觸發；人物在 14.0）"), (25.0, "避難所的燈火（妻子在 26.6）"), (33.6, "走向舊家（綠色路牌）")]
for x, lab in pts:
    dot(*P(x, -1.85), 5, "#e0b040")
    text(P(x, -1.85)[0] + 7, P(x, -1.85)[1] - 6, lab, 12, "#f0d080")
rect(*P(33.4, -2.5), *P(33.8, -2.7), "#2a6a4a", "#ffffff")
# 擋路的拒馬（前後都能繞）
rect(*P(17.75, 0.45), *P(19.75, 0.1), "#6a5038", "#ff9a3a")
text(P(16.4, 1.3)[0], P(0, 1.3)[1] - 2, "拒馬＋鐵絲網（擋路，前後都能繞）", 12, "#ffb070")
# 地上零星的小火、前景
for x, z in ((10.8, -3.6), (23.6, 2.9), (34.8, -3.5)):
    dot(*P(x, z), 4, "#ff9a3a")
text(P(23.8, 3.0)[0], P(0, 3.0)[1] - 4, "地上的小火（前景）", 10, "#ffb070")
for x, lab in ((5.5, "燒焦的木板"), (9.7, "倒下的禁止進入牌"), (15.0, "碎石"), (21.0, "磚塊"), (28.4, "燒焦的木板"), (31.9, "倒下的牌子")):
    dot(*P(x, 2.3), 3, "#a09080")
    text(P(x, 2.3)[0] + 4, P(x, 2.3)[1] + 4, lab, 10, "#c0b0a0")
for x, lab in ((6.6, "斷牆（前景，低）"), (16.5, "鋼筋（前景）"), (22.0, "斷牆（前景）"), (30.8, "鋼筋")):
    rect(*P(x - 0.6, 3.6), *P(x + 0.6, 3.3), "#5a524a")
    text(P(x - 0.6, 3.6)[0], P(0, 3.6)[1] - 3, lab, 10, "#d0c4b0")
text(P(0, 4.6)[0], P(0, 4.6)[1], "出生點 x 3.4", 11, "#a0a0a0")
for x in range(0, 37, 6):
    text(P(x, -14)[0] - 6, P(0, -14)[1] + 16, f"{x}", 11, "#888")

# ---------- 剖面圖：1 m＝22 px；z=+8 在左、z=−30 在右 ----------
SX, SOX, SOY = 22.0, 40.0, 1080.0
def S(z, y):
    return SOX + (8 - z) * SX, SOY - y * SX

text(20, 680, "剖面圖（側面看：左＝鏡頭，右＝遠方；斷牆的缺口看得到天空）", 17)
rect(*S(4.2, 0), *S(-11, -0.3), "#4a443c")
rect(*S(-3.3, 0.15), *S(-5.2, 0), "#6a5e50")
rect(*S(-5.2, 8), *S(-11, 0), "#4e4640")                        # 高的空殼
rect(*S(-5.2, 3), *S(-11, 0), "#5a524a")                        # 塌剩一層（缺口處）
text(S(-5.4, 8)[0], S(0, 8)[1] - 4, "高的空殼 7～8 m", 11)
text(S(-5.4, 3)[0] + 40, S(0, 3)[1] - 4, "塌剩一層 3 m", 11)
for k, (z0, top) in enumerate(((-13, 10), (-17, 13), (-21, 11))):
    rect(*S(z0, top), *S(z0 - 3, 0), ("#5a3826", "#4e3224", "#44302a")[k])
text(S(-14, 15)[0], S(0, 15)[1] - 4, "遠處剪影（從缺口看得到）", 11, "#e0b080")
rect(*S(-2.4, 2.0), *S(-2.8, 0), "#8a8e90")                      # 圍欄
text(S(-2.0, 2.4)[0] - 30, S(0, 2.4)[1], "圍欄 2 m", 11, "#c8d0d8")
dot(*S(-2.4, 0.5), 5, "#ff8a20")
p, q = S(1.5, 0); r, s = S(-1.5, 0)
line(p, q - 3, r, s - 3, "#e0b040", 4)
rect(*S(0.45, 0.9), *S(0.1, 0), "#6a5038")                       # 拒馬
text(S(1.2, 1.3)[0], S(0, 1.3)[1], "拒馬 0.9 m", 11, "#ffb070")
rect(*S(3.6, 1.2), *S(3.3, 0), "#5a524a")                        # 前景斷牆
text(S(4.8, 1.5)[0], S(0, 1.5)[1], "前景斷牆", 11)
p, q = S(7.17, 2.23)
dot(p, q, 6, "#ff8060")
text(p - 20, q - 12, "鏡頭 B", 12, "#ff9a80")
for ang in (15, -25):
    dz = -24 - 7.17
    r, s = S(-24, 2.23 + math.tan(math.radians(ang)) * abs(dz))
    line(p, q, r, s, "#ff806080", 1)
text(S(4.0, 7.4)[0], S(0, 7.4)[1], "鏡頭在斷牆前看得到約 5.5 m 高，", 11)
text(S(4.0, 6.6)[0], S(0, 6.6)[1], "缺口（塌剩一層）上面看得到天空", 11)

# ---------- 配色 ----------
text(820, 690, "配色（固有色；黃昏的光、火光交給燈光）", 17)
pal = [("#4a443c", "柏油路（裂縫）"), ("#6a6258", "水泥（斷牆、樓板）"), ("#6e4a36", "磚"), ("#2a2622", "焦黑"),
       ("#8a7a5a", "沙包"), ("#6a5038", "木頭（拒馬）"), ("#8a8e90", "鐵絲網、鋼筋"), ("#6a5a48", "鐵皮（避難所，鏽）"),
       ("#2a6a4a", "綠色路牌"), ("#d0a050", "天空（地平線，煙霧）"), ("#4a3a30", "天空（上方）"), ("#ff9a3a", "火、營火")]
for i, (c, n) in enumerate(pal):
    x = 820 + (i % 2) * 290
    y = 720 + (i // 2) * 42
    rect(x, y, x + 54, y + 32, c, "#888")
    text(x + 64, y + 22, f"{n}  {c}", 13)
text(820, 990, "燈光：夕陽方向光（暗金色、有陰影）、環境光暖色、", 13, "#c0c0c0")
text(820, 1012, "火桶 ×2 與地上小火的火光（跳動）、避難所的暖光（窗戶＋營火）；", 13, "#c0c0c0")
text(820, 1034, "灰燼粒子、煙霧留到 B5。", 13, "#c0c0c0")

mvg = OUT + ".mvg"
open(mvg, "w", encoding="utf-8").write("\n".join(cmds) + "\n")
subprocess.run(["magick", "-size", f"{W}x{H}", "xc:#1a1c1e", "-draw", f"@{mvg}", OUT], check=True)
