# B3-3a 設施走廊的配置圖：上＝俯視圖（x −2～38 m、z −8～＋5）、下左＝剖面圖（從側面看鏡頭 B、天花板的管線、實驗室、警報燈）、下右＝配色。
# 用法：python3 art/design/b3/lab_layout.py 輸出.png（ImageMagick 的 MVG；中文字用 STHeiti）
# 互動點、掩護、通風管的位置照 Lab3D（B1 由 2D 轉換）不變；警衛巡視與躲藏的判定都靠這些位置。
import math, subprocess, sys

OUT = sys.argv[1]
FONT = "/System/Library/Fonts/STHeiti Medium.ttc"
W, H = 1400, 1000
cmds = [f"viewbox 0 0 {W} {H}", f"font '{FONT}'"]


def rect(x0, y0, x1, y1, fill, stroke="none"):
    cmds.append(f"fill '{fill}' stroke '{stroke}' stroke-width 1 rectangle {x0:.1f},{y0:.1f} {x1:.1f},{y1:.1f}")


def line(x0, y0, x1, y1, color, width=1):
    cmds.append(f"stroke '{color}' stroke-width {width} fill none line {x0:.1f},{y0:.1f} {x1:.1f},{y1:.1f}")


def dot(x, y, r, color):
    cmds.append(f"fill '{color}' stroke none circle {x:.1f},{y:.1f} {x + r:.1f},{y:.1f}")


def poly(pts, fill):
    cmds.append(f"fill '{fill}' stroke none polygon " + " ".join(f"{x:.1f},{y:.1f}" for x, y in pts))


def text(x, y, s, size=13, color="#e8e8e8"):
    s = s.replace("'", "\\'")
    cmds.append(f"stroke none fill '{color}' font-size {size} text {x:.1f},{y:.1f} '{s}'")


WALL = -3.6        # 後牆（走廊比診所窄）；後面是實驗室，窗戶看得到裡面
ROOM = -7.0        # 實驗室的深度

# ---------- 俯視圖：1 m＝33 px；x=−2 在左；z=+5 在上（鏡頭這一側），往下是 z 變小（往裡面） ----------
PX, OX, OY = 33.0, 30.0, 60.0
def P(x, z):
    return OX + (x + 2) * PX, OY + (5 - z) * PX

text(20, 34, "俯視圖（上＝鏡頭這一側，下＝後牆與實驗室；單位公尺；區域 x 0～36；天花板 3 m）", 19)
rect(*P(-2, 5), *P(38, -8), "#1a1c1e")
rect(*P(0, 4.2), *P(36, WALL), "#5e5a52")                        # 地板（塑膠地磚）
for x in range(0, 37):
    line(*P(x, 4.2), *P(x, WALL), "#545048")
rect(*P(0, 1.5), *P(36, -1.5), "#6e6a60")                       # 走道
text(P(0.2, 0)[0], P(0, 0.3)[1], "走道 z −1.5～＋1.5", 12, "#1e1c18")
rect(*P(0, WALL), *P(36, WALL - 0.3), "#8a8676", "#b8b4a0")       # 後牆（z −3.6）
rect(*P(-0.4, 4.2), *P(0, WALL - 0.3), "#8a8676"); rect(*P(36, 4.2), *P(36.4, WALL - 0.3), "#8a8676")
rect(*P(0, WALL - 0.3), *P(36, ROOM), "#2a2e30")                  # 後面的實驗室（暗）
text(P(0.3, -6.6)[0], P(0, -6.6)[1], "實驗室（暗；實驗桌、螢幕的微光；隔牆分成幾間）", 12, "#9aa8a8")
for x in (6.2, 13.0, 19.0, 26.6, 32.0):
    line(*P(x, WALL - 0.3), *P(x, ROOM), "#6a6a60", 2)
# 觀察窗（玻璃破了）
for x0, x1 in ((1.0, 3.0), (8.4, 10.4), (14.0, 16.0), (19.6, 21.6), (27.4, 29.4)):
    rect(*P(x0, WALL + 0.05), *P(x1, WALL - 0.35), "#7a9aa8")
text(P(14.0, -4.5)[0], P(0, -4.5)[1] + 4, "觀察窗 ×5（破的，看得到裡面）", 12, "#a8c8d8")
# 起火的實驗室（門開著，火從門口竄出來）
rect(*P(6.6, WALL + 0.05), *P(7.8, WALL - 0.35), "#2a1408")
rect(*P(6.3, WALL - 0.4), *P(9.0, -6.0), "#7a3010")
for k in range(5):
    dot(*P(6.8 + k * 0.45, -4.6 - (k % 2) * 0.5), 6, "#ff8a20")
dot(*P(7.2, -3.3), 5, "#ffb040")
text(P(5.0, -5.4)[0], P(0, -5.4)[1], "起火的實驗室（像素火焰＋火光）", 12, "#ffb070")
# 靠牆的東西
furn = [(4.6, 5.8, -3.15, -3.55, "#7a7e80", "實驗架"), (11.2, 12.4, -3.15, -3.55, "#7a7e80", "實驗架"),
        (25.0, 26.2, -3.15, -3.55, "#7a7e80", "實驗架")]
for x0, x1, z0, z1, c, lab in furn:
    rect(*P(x0, z0), *P(x1, z1), c, "#c8c8c0")
    text(P(x0, z0)[0], P(0, z0)[1] - 4, lab, 11, "#d8d8d0")
# 通風管口（牆腳）
rect(*P(23.8, WALL + 0.1), *P(24.5, WALL - 0.1), "#4a5054", "#e0e0e0")
text(P(23.0, -2.6)[0], P(0, -2.6)[1] + 26, "通風管口", 11, "#d0d8e0")
rect(*P(30.1, WALL + 0.1), *P(30.8, WALL - 0.1), "#4a5054", "#e0e0e0")
line(*P(30.1, -3.0), *P(30.9, -2.7), "#a0a8b0", 3)                 # 踢掉的格柵蓋在地上
text(P(29.6, -2.6)[0], P(0, -2.6)[1] + 26, "通風管出口（蓋子掉在地上）", 11, "#d0d8e0")
line(*P(24.15, WALL - 0.5), *P(30.45, WALL - 0.5), "#a0a8b080", 3)  # 牆裡的通風管
# 出口：後牆的鐵門被撞開、外面有光
rect(*P(33.0, WALL + 0.05), *P(34.4, WALL - 0.35), "#f0e0a0")
poly([P(33.0, WALL), P(34.4, WALL), P(35.2, -1.5), P(32.4, -1.5)], "#f0e0a030")
text(P(32.0, -4.5)[0], P(0, -4.5)[1] + 4, "出口（鐵門被撞開，外面亮）", 12, "#f8e8b0")
# 警報燈（後牆上 2.5 m）
for x in (3.75, 16.9, 26.6):
    dot(*P(x, WALL + 0.15), 6, "#ff2a1a")
    text(P(x, WALL)[0] - 16, P(0, WALL)[1] + 22, "警報燈", 11, "#ff8070")
# 互動點
pts = [(10.94, -0.02, "女科學家（靠近就觸發）"), (17.97, -1.85, "實驗紀錄（倒下的檔案櫃）"),
       (24.14, -1.85, "通風管（鑽到 30.5）"), (33.59, -1.85, "逃出設施")]
for x, z, lab in pts:
    dot(*P(x, z), 5, "#e0b040")
    tx = P(x - 4.4, z)[0] if x < 12 else P(x, z)[0] + 7                  # 女科學家的字放左邊，不壓到推車
    text(tx, P(x, z)[1] - 6, lab, 12, "#f0d080")
rect(*P(17.2, -2.6), *P(18.8, -3.5), "#6a6a5a", "#ffffff")       # 倒下的檔案櫃＋散落的紀錄
# 掩護（擋路，在走道上）
rect(*P(14.2, 0.55), *P(15.5, -0.05), "#8a8e90", "#7ad0ff")
text(P(13.6, 1.3)[0], P(0, 1.3)[1] - 2, "推車（掩護）", 12, "#9ad8ff")
rect(*P(22.1, 0.55), *P(23.2, -0.05), "#8a6a40", "#7ad0ff")
text(P(21.4, 1.3)[0], P(0, 1.3)[1] - 2, "木箱（掩護）", 12, "#9ad8ff")
# 警衛與手電筒照到的地面（朝左 4 秒、朝右 3 秒）
gx = 25.78
dot(*P(gx, -0.02), 6, "#ff6040")
text(P(gx, 0)[0] + 8, P(0, 0)[1] - 8, "警衛（巡視）", 12, "#ff9a80")
poly([P(gx, 0), P(gx - 4.16, 1.4), P(gx - 4.16, -1.4)], "#ffe0a040")
poly([P(gx, 0), P(gx + 4.16, 1.4), P(gx + 4.16, -1.4)], "#ffe0a020")
text(P(gx + 0.4, -1.0)[0], P(0, -1.0)[1], "手電筒照到地面 4.2 m（左 4 秒／右 3 秒）", 11, "#ffe0a0")
# 前景
for x, lab in ((5.2, "藥瓶"), (9.4, "電線"), (19.5, "碎玻璃"), (22.7, "紀錄夾"), (28.9, "紙"), (32.0, "藥瓶")):
    dot(*P(x, 2.3), 3, "#a09080")
    text(P(x, 2.3)[0] + 4, P(x, 2.3)[1] + 4, lab, 10, "#c0b0a0")
for x in (13.0, 31.5):
    rect(*P(x - 0.15, 3.4), *P(x + 0.15, 3.1), "#c8a040")
    text(P(x - 0.4, 3.4)[0], P(0, 3.4)[1] - 3, "垂下的電線＋火花（前景）", 10, "#e0c070")
text(P(0, 4.6)[0], P(0, 4.6)[1], "出生點 x 3.4", 11, "#a0a0a0")
for x in range(0, 37, 6):
    text(P(x, -8)[0] - 6, P(0, -8)[1] + 16, f"{x}", 11, "#888")

# ---------- 剖面圖：1 m＝40 px；z=+8 在左、z=−7.5 在右 ----------
SX, SOX, SOY = 40.0, 40.0, 960.0
def S(z, y):
    return SOX + (8 - z) * SX, SOY - y * SX

text(20, 560, "剖面圖（側面看：左＝鏡頭，右＝後牆與實驗室）", 17)
rect(*S(4.2, 0), *S(ROOM, -0.3), "#5e5a52")                     # 地板
rect(*S(4.2, 3.0), *S(WALL, 3.2), "#6a6660")                    # 天花板（輕鋼架，掉了幾片）
for z in (2.6, 0.5, -1.6, -3.0):
    dot(*S(z, 2.75), 5, "#8a8e90")                              # 管線
text(S(4.0, 3.2)[0], S(0, 3.2)[1] - 8, "天花板 3 m：外露的管線、電纜架，掉了幾片", 12)
rect(*S(WALL, 3.2), *S(WALL - 0.3, 0), "#8a8676")               # 後牆
rect(*S(WALL, 2.2), *S(WALL - 0.3, 1.0), "#7a9aa8")             # 觀察窗
rect(*S(WALL, 1.0), *S(WALL - 0.3, 0.95), "#5a4a3a")
text(S(-1.7, 0.6)[0], S(0, 0.6)[1], "護牆木條 1 m →", 11, "#c8b090")
dot(*S(WALL + 0.1, 2.55), 6, "#ff2a1a")
text(S(-1.2, 2.9)[0], S(0, 2.9)[1] - 4, "警報燈 2.5 m →", 12, "#ff8070")
rect(*S(WALL - 0.3, 2.8), *S(ROOM, 3.0), "#6a6660"); rect(*S(ROOM, 3.0), *S(ROOM - 0.3, 0), "#8a8676")
rect(*S(-4.8, 0.9), *S(-6.0, 0), "#4a5054")                     # 實驗桌
text(S(-4.2, 1.8)[0], S(0, 1.8)[1], "實驗室（實驗桌、螢幕）", 12, "#9aa8a8")
rect(*S(-3.15, 1.9), *S(-3.55, 0), "#7a7e80")                   # 實驗架
text(S(-0.9, 2.1)[0], S(0, 2.1)[1], "實驗架 1.9 m →", 12)
rect(*S(WALL + 0.02, 0.6), *S(WALL - 0.1, 0.05), "#4a5054")      # 通風管口
p, q = S(1.5, 0); r, s = S(-1.5, 0)
line(p, q - 3, r, s - 3, "#e0b040", 4)
rect(*S(0.5, 0.95), *S(0.0, 0), "#8a8e90")                      # 推車（掩護）
text(S(0.9, 1.25)[0], S(0, 1.25)[1], "推車／木箱 約 1 m（躲在後面）", 11, "#9ad8ff")
rect(*S(3.4, 3.0), *S(3.1, 1.7), "#c8a040")                     # 垂下的電線
text(S(4.6, 1.4)[0], S(0, 1.4)[1], "垂下的電線", 12, "#e0c070")
p, q = S(7.17, 2.23)
dot(p, q, 6, "#ff8060")
text(p - 20, q - 12, "鏡頭 B", 12, "#ff9a80")
for ang in (15, -25):
    dz = -7.5 - 7.17
    r, s = S(-7.5, 2.23 + math.tan(math.radians(ang)) * abs(dz))
    line(p, q, r, s, "#ff806080", 1)

# ---------- 配色 ----------
text(820, 560, "配色（固有色；暗的感覺交給燈光：紅色警報＋火光）", 17)
pal = [("#8a8676", "牆（上：灰白漆、髒）"), ("#5a4a3a", "護牆（下：深色木板）"), ("#6e6a60", "地板（塑膠地磚）"),
       ("#6a6660", "天花板"), ("#8a8e90", "金屬（架子、推車、管線）"), ("#7a9aa8", "玻璃（觀察窗）"),
       ("#8a6a40", "木箱"), ("#4a5054", "通風管、實驗桌"), ("#ff2a1a", "警報燈"), ("#ff8a20", "火"),
       ("#f0e0a0", "出口外的光"), ("#2a2622", "焦黑")]
for i, (c, n) in enumerate(pal):
    x = 820 + (i % 2) * 290
    y = 590 + (i // 2) * 42
    rect(x, y, x + 54, y + 32, c, "#888")
    text(x + 64, y + 22, f"{n}  {c}", 13)
text(820, 862, "燈光：環境光很暗、偏紅；警報燈 ×3 紅色閃（＋警報聲）；", 13, "#c0c0c0")
text(820, 884, "起火的實驗室：橘色火光跳動；出口：門外的亮光；", 13, "#c0c0c0")
text(820, 906, "實驗室：螢幕的青綠微光；警衛手電筒（唯一有陰影）＋主角的手電筒。", 13, "#c0c0c0")

mvg = OUT + ".mvg"
open(mvg, "w", encoding="utf-8").write("\n".join(cmds) + "\n")
subprocess.run(["magick", "-size", f"{W}x{H}", "xc:#1a1c1e", "-draw", f"@{mvg}", OUT], check=True)
