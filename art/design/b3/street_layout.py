# B3-1a 街道的配置圖：上＝俯視圖（x −6～42 m、z −20～＋6）、下左＝剖面圖（從側面看鏡頭 B 和樓房、巷口、遠景）、下右＝配色。
# 用法：python3 art/design/b3/street_layout.py 輸出.png（ImageMagick 的 MVG；中文字用 STHeiti）
import math, subprocess, sys

OUT = sys.argv[1]
FONT = "/System/Library/Fonts/STHeiti Medium.ttc"
W, H = 1400, 1240
cmds = [f"viewbox 0 0 {W} {H}", f"font '{FONT}'"]


def rect(x0, y0, x1, y1, fill, stroke="none"):
    cmds.append(f"fill '{fill}' stroke '{stroke}' stroke-width 1 rectangle {x0:.1f},{y0:.1f} {x1:.1f},{y1:.1f}")


def line(x0, y0, x1, y1, color, width=1):
    cmds.append(f"stroke '{color}' stroke-width {width} fill none line {x0:.1f},{y0:.1f} {x1:.1f},{y1:.1f}")


def dot(x, y, r, color):
    cmds.append(f"fill '{color}' stroke none circle {x:.1f},{y:.1f} {x + r:.1f},{y:.1f}")


def text(x, y, s, size=13, color="#e8e8e8"):
    s = s.replace("'", "\\'")
    cmds.append(f"stroke none fill '{color}' font-size {size} text {x:.1f},{y:.1f} '{s}'")


# ---------- 俯視圖：1 m＝27 px；x=−6 在左；z=+6 在上（鏡頭這一側），往下是 z 變小（往裡面） ----------
PX, OX, OY = 27.0, 40.0, 60.0
def P(x, z):
    return OX + (x + 6) * PX, OY + (6 - z) * PX

text(20, 34, "俯視圖（上＝鏡頭這一側，下＝遠方；單位公尺；區域 x 0～36）", 19)
a, b = P(-6, 6); c, d = P(42, -20)
rect(a, b, c, d, "#2a221c")
rect(*P(-6, 6), *P(42, 2.6), "#5e554a")                          # 前人行道
rect(*P(-6, 2.6), *P(42, -3.3), "#4a443c")                       # 馬路
rect(*P(-6, 1.5), *P(42, -1.5), "#57504a")                       # 走道（主角能走的）
text(P(36.4, 0)[0], P(0, 0.3)[1], "走道 z −1.5～＋1.5", 12)
for x in range(-6, 42, 3):                                       # 中央的黃色虛線
    line(*P(x, -0.6), *P(x + 1.6, -0.6), "#b8963c", 2)
rect(*P(-6, -3.3), *P(42, -5.2), "#6a5e50")                      # 後人行道（高 15 cm 的路緣）
# 塌陷的洞（照原圖；在走道後面、不會走進去）
cmds.append(f"fill '#141102' stroke '#5a4a3a' stroke-width 1 ellipse {P(17.8, -2.5)[0]:.1f},{P(0, -2.5)[1]:.1f} {1.9 * PX:.1f},{0.8 * PX:.1f} 0,360")
text(P(15.4, -2.5)[0], P(0, -3.0)[1] + 14, "塌陷的洞", 12, "#c8b8a0")
# 樓房（前面 z −5.2、深 6 m），兩條巷口
blocks = [(-6, 8.5, "店面 A＋停車場入口"), (10.5, 20, "店面 B"), (20, 27, "店面 A"), (30, 36, "店面 B"), (36, 42, "診所（綠十字）")]
for x0, x1, lab in blocks:
    rect(*P(x0, -5.2), *P(x1, -11.2), "#6e4a36", "#a07a5a")
    text(P(x0 + 0.3, -6)[0], P(0, -6)[1] + 4, lab, 12)
rect(*P(0, -5.2), *P(3, -6.4), "#1a1410")                        # 停車場入口（往下的坡道）
for x0, x1, lab in ((8.5, 10.5, "巷口"), (27, 30, "巷口（較寬）")):
    rect(*P(x0, -5.2), *P(x1, -20), "#3a2e24")
    text(P(x0 + 0.1, -12)[0], P(0, -12)[1], lab, 12, "#e0b080")
for x0, x1, z0, z1 in ((4, 8.3, -13, -16), (11, 16, -14, -18), (24, 26.8, -13, -17), (30.2, 35, -13, -19)):
    rect(*P(x0, z0), *P(x1, z1), "#5a3826")                     # 遠處建築剪影
text(P(12, -18.6)[0], P(0, -18.6)[1] + 4, "遠處建築剪影（z −13～−40）＋夕陽漸層天空（最後面）", 12, "#e0b080")
# 互動點
for x, z, lab in ((1.1, -1.85, "回停車場"), (13.3, 0.1, "燃燒的車（擋路）"), (22.66, -1.85, "尋人啟事（電線桿）"), (33.6, -1.85, "往診所")):
    dot(*P(x, z), 5, "#e0b040")
    text(P(x, z)[0] + 7, P(x, z)[1] - 6, lab, 12, "#f0d080")
# 燃燒的車（擋路，可以從前面或後面繞）
rect(*P(11.15, 0.95), *P(15.45, -0.75), "#2a2420", "#ff9a3a")
# 停著的廢車
for x, z in ((3.6, -2.6), (26.0, -2.6)):
    rect(*P(x - 2.15, z + 0.9), *P(x + 2.15, z - 0.9), "#3a3028", "#9a8a7a")
text(P(24, -2.6)[0], P(0, -2.6)[1] + 22, "廢車", 12)
# 公車亭、電線桿、路燈、地上小物
for x in (5.2, 29.1):
    rect(*P(x - 1.5, -3.9), *P(x + 1.5, -4.9), "#55606a", "#c0d0d4")
text(P(29.3, -4.2)[0], P(0, -4.2)[1] + 4, "公車亭", 12)
for x, lab in ((7.3, "電線桿（傾斜）"), (22.66, "")):
    dot(*P(x, -3.5), 4, "#9a8a7a")
    if lab:
        text(P(x, -3.5)[0] + 6, P(0, -3.5)[1] + 4, lab, 11)
for x in (6.6, 30.5):
    dot(*P(x, 3.3), 4, "#d8f0ff")
text(P(6.9, 3.3)[0], P(0, 3.3)[1] + 4, "路燈（前景）", 11)
for x, lab in ((4.7, "磚"), (8.75, "輪胎"), (15.9, "木板"), (19.4, "玻璃"), (26.6, "紙"), (29.7, "磚"), (19.5, ""), (28.0, "")):
    z = 2.2 if lab else 3.8
    dot(*P(x, z), 3, "#a08a70")
    text(P(x, z)[0] + 4, P(x, z)[1] + 4, lab or "碎石（前景）", 10, "#c0b0a0")
for x in range(0, 37, 6):
    text(P(x, -20)[0] - 6, P(0, -20)[1] + 16, f"{x}", 11, "#888")
# 鏡頭 B 在主角深度的視野（主角在 x 13）
line(*P(13 - 3.93, 0), *P(13 + 3.93, 0), "#ff8060", 2)

# ---------- 剖面圖：1 m＝18 px；z=+8 在左、z=−40 在右 ----------
SX, SOX, SOY = 12.0, 40.0, 1200.0
def S(z, y):
    return SOX + (8 - z) * SX, SOY - y * SX

text(20, 800, "剖面圖（側面看：左＝鏡頭，右＝遠方；樓房上方是天空）", 17)
rect(*S(8, 0), *S(-40, -0.4), "#4a443c")
rect(*S(-5.2, 8), *S(-11.2, 0), "#6e4a36")                       # 樓房
text(S(-5.4, 8)[0], S(0, 8)[1] - 4, "樓房 2～3 層（約 8 m）", 11)
rect(*S(-14, 10), *S(-18, 0), "#5a3826"); rect(*S(-26, 14), *S(-32, 0), "#4a3020")
text(S(-14, 14)[0], S(0, 14)[1] - 4, "遠處剪影（越遠越暗、越淡）", 11, "#e0b080")
rect(*S(-36, 16), *S(-37, 0), "#c87a3a")
text(S(-33, 16)[0] - 60, S(0, 16)[1] - 4, "夕陽天空", 11, "#e0b080")
p, q = S(1.5, 0); r, s = S(-1.5, 0)
line(p, q - 3, r, s - 3, "#e0b040", 4)
rect(*S(0.1, 1.5), *S(-0.1, 0), "#c8b890")
p, q = S(7.17, 2.23)
dot(p, q, 6, "#ff8060")
text(p - 30, q - 12, "鏡頭 B", 12, "#ff9a80")
for ang in (15, -25):
    dz = -40 - 7.17
    r, s = S(-40, 2.23 + math.tan(math.radians(ang)) * abs(dz))
    line(p, q, r, s, "#ff806080", 1)
text(S(-6, 5.6)[0] + 4, S(0, 5.6)[1], "← 鏡頭在樓房前面看得到約 5.5 m 高，", 11)
text(S(-6, 4.6)[0] + 4, S(0, 4.6)[1], "　 天空主要從巷口和樓頂上方露出來", 11)

# ---------- 配色 ----------
text(800, 800, "配色（固有色；暗的感覺交給燈光）", 17)
pal = [("#4a443c", "柏油路"), ("#6a5e50", "人行道"), ("#6e4a36", "磚牆"), ("#5a4232", "暗磚、窗台"),
       ("#b8963c", "黃色標線"), ("#2a2420", "燒焦"), ("#3a3028", "廢車"), ("#c8bca0", "尋人啟事、紙"),
       ("#d0803a", "天空（地平線）"), ("#6e3c24", "天空（上方）"), ("#5a3826", "遠處剪影"), ("#ff9a3a", "火、火光")]
for i, (c, n) in enumerate(pal):
    x = 800 + (i % 2) * 290
    y = 830 + (i // 2) * 42
    rect(x, y, x + 54, y + 32, c, "#888")
    text(x + 64, y + 22, f"{n}  {c}", 13)

mvg = OUT + ".mvg"
open(mvg, "w", encoding="utf-8").write("\n".join(cmds) + "\n")
subprocess.run(["magick", "-size", f"{W}x{H}", "xc:#1d2224", "-draw", f"@{mvg}", OUT], check=True)
